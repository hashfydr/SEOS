import { useStore } from '../store';

/**
 * Compiles the entire active project into a formal IEEE 830 compliant Software Specification Document in Markdown.
 */
export function generateIEEE830Markdown(): string {
  const s = useStore.getState();
  const dateStr = new Date().toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  const approvedReqs = s.requirements.filter((r) => r.status === 'approved');
  const approvedStories = s.userStories.filter((st) => st.status === 'approved');

  let md = `# Software Requirements & System Architecture Specification (SRS)
**Project Title:** ${s.projectName}  
**Date of Specification:** ${dateStr}  
**Specification Standard:** IEEE 830 / ISO/IEC/IEEE 29148  
**Author / Engineering Cohort:** ${s.currentUser ? `${s.currentUser.name} (${s.currentUser.role.toUpperCase()})` : 'SEOS Engineering Team'}  
${s.currentUser?.classroom_code ? `**Classroom / Cohort Code:** ${s.currentUser.classroom_code}\n` : ''}
---

## 1. Project Overview & Vision

${s.productIdea || 'No project description provided.'}

* **Total Elicited Requirements:** ${s.requirements.length} (${approvedReqs.length} Approved)
* **Mapped User Stories:** ${s.userStories.length} (${approvedStories.length} Approved)
* **Domain Entities:** ${s.umlNodes.length}
* **Architectural Pattern:** ${s.architecture.pattern || 'Not Selected'}

---

## 2. Software Requirements Specification (IEEE 830)

| Requirement ID | Type | Priority | Description | Status |
| :--- | :--- | :--- | :--- | :--- |
${s.requirements
  .map(
    (r) =>
      `| **${r.id}** | ${r.type} | \`${r.priority}\` | ${r.description.replace(/\|/g, '\\|')} | **[${r.status.toUpperCase()}]** |`
  )
  .join('\n')}

---

## 3. Agile User Stories & Acceptance Criteria

${s.userStories
  .map(
    (st) => `### ${st.id}: As a ${st.role}
* **Goal:** I want to ${st.action}
* **Benefit:** So that ${st.benefit}
* **Traceable REQ ID:** \`${st.reqId || 'N/A'}\`
* **Status:** **[${st.status.toUpperCase()}]**
* **Verification Criteria (Gherkin BDD):**
${
  st.criteria && st.criteria.length > 0
    ? st.criteria.map((c) => `  * Given/When/Then: ${c}`).join('\n')
    : '  * No acceptance criteria specified.'
}
`
  )
  .join('\n')}

---

## 4. Domain & Data Architecture (3NF Entities)

${s.umlNodes
  .map(
    (node) => `### Entity: \`${node.name}\`
* **Attributes:**
${node.fields
  .map(
    (f) =>
      `  * \`${f.name}\`: \`${f.type}\`${f.pk ? ' **[PRIMARY KEY]**' : ''}${f.fk ? ' **[FOREIGN KEY]**' : ''}`
  )
  .join('\n')}
${
  node.methods && node.methods.length > 0
    ? `* **Domain Operations:**\n${node.methods.map((m) => `  * \`${m}\``).join('\n')}`
    : ''
}
`
  )
  .join('\n')}

${
  s.umlEdges.length > 0
    ? `### Relational Cardinalities
${s.umlEdges.map((e) => `* \`${e.from}\` ──[${e.label || 'relates to'}]──> \`${e.to}\``).join('\n')}
`
    : ''
}

---

## 5. Architectural Pattern & Scalability Trade-Offs

* **Recommended Architecture:** **${s.architecture.pattern || 'Pending'}**
* **Architectural Rationale:**  
  ${s.architecture.rationale || 'Architectural rationale grounded in domain requirements.'}

### Decomposed Components
| Component Name | Primary Technology | Responsibility |
| :--- | :--- | :--- |
${
  s.architecture.components && s.architecture.components.length > 0
    ? s.architecture.components.map((c) => `| **${c.name}** | \`${c.tech}\` | ${c.purpose} |`).join('\n')
    : '| N/A | N/A | No components defined yet |'
}

### Evaluated Trade-offs
${
  s.architecture.tradeoffs && s.architecture.tradeoffs.length > 0
    ? s.architecture.tradeoffs
        .map((t) => `* **Advantage:** ${t.pro}\n* **Constraint:** ${t.con}`)
        .join('\n\n')
    : '* Standard scalability trade-offs evaluated.'
}

---

## 6. OpenAPI 3.1 REST API Contract

\`\`\`yaml
${s.openapiYaml || '# No OpenAPI specification generated yet.'}
\`\`\`

---

## 7. Grounded Literature & Standards References

${
  s.architecture.citations && s.architecture.citations.length > 0
    ? s.architecture.citations
        .map((c) => `* **${c.source || 'Software Engineering Literature'}:** ${c.title || ''}`)
        .join('\n')
    : `* **Martin Kleppmann:** *Designing Data-Intensive Applications* (O'Reilly)
* **Sam Newman:** *Building Microservices: Designing Fine-Grained Systems* (O'Reilly)
* **Eric Evans:** *Domain-Driven Design: Tackling Complexity in Software* (Addison-Wesley)
* **Robert C. Martin:** *Clean Architecture: A Craftsman's Guide* (Prentice Hall)`
}

---
*Generated by SEOS (Software Engineering Operating System) — UCS 503 Coursework Platform.*
`;

  return md;
}

/**
 * Triggers a browser download of the complete project specification as a Markdown file (.md).
 */
export function exportProjectAsMarkdown(): void {
  const s = useStore.getState();
  const mdContent = generateIEEE830Markdown();
  const safeTitle = s.projectName.replace(/[^a-zA-Z0-9_-]/g, '_') || 'SEOS_Project';
  const blob = new Blob([mdContent], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${safeTitle}_SRS_Specification.md`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/**
 * Formats a clean print-ready stylesheet and triggers the browser Print dialog to save as PDF.
 */
export function exportProjectAsPDF(): void {
  const s = useStore.getState();
  const mdContent = generateIEEE830Markdown();

  // Create an isolated printable iframe
  const printWindow = window.open('', '_blank');
  if (!printWindow) {
    alert('Please allow popups to export PDF.');
    return;
  }

  // Convert basic Markdown to readable HTML for print
  const htmlContent = mdContent
    .replace(/^# (.*$)/gim, '<h1 class="text-2xl font-bold border-b pb-2 mb-4">$1</h1>')
    .replace(/^## (.*$)/gim, '<h2 class="text-xl font-bold mt-6 mb-3 border-b pb-1">$1</h2>')
    .replace(/^### (.*$)/gim, '<h3 class="text-base font-bold mt-4 mb-2">$1</h3>')
    .replace(/\*\*(.*?)\*\*/gim, '<strong>$1</strong>')
    .replace(/\*(.*?)\*/gim, '<em>$1</em>')
    .replace(/`([^`]+)`/gim, '<code class="bg-gray-100 px-1 py-0.5 rounded text-sm">$1</code>')
    .replace(/^\* (.*$)/gim, '<li class="ml-4 list-disc">$1</li>')
    .replace(/```yaml([\s\S]*?)```/gim, '<pre class="bg-gray-50 border p-3 rounded font-mono text-xs overflow-x-auto">$1</pre>')
    .replace(/\n\n/gim, '<p class="my-2"></p>');

  printWindow.document.write(`
    <!DOCTYPE html>
    <html>
      <head>
        <title>${s.projectName} — SRS Specification</title>
        <style>
          body {
            font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif;
            line-height: 1.6;
            color: #1a1a1a;
            padding: 30px;
            max-width: 800px;
            margin: 0 auto;
          }
          h1 { color: #a4502b; border-bottom: 2px solid #a4502b; }
          h2 { color: #2a231c; border-bottom: 1px solid #e2d8c6; margin-top: 24px; }
          table { width: 100%; border-collapse: collapse; margin: 16px 0; font-size: 13px; }
          th, td { border: 1px solid #ddd; padding: 8px; text-align: left; }
          th { background-color: #f7f4ee; font-weight: bold; }
          pre { background-color: #f7f4ee; border: 1px solid #e2d8c6; padding: 12px; border-radius: 6px; font-family: monospace; font-size: 11px; white-space: pre-wrap; }
          code { font-family: monospace; background: #ece5d8; padding: 2px 4px; border-radius: 4px; }
          @media print {
            body { padding: 0; }
            h2 { page-break-before: auto; }
          }
        </style>
      </head>
      <body>
        ${htmlContent}
        <script>
          window.onload = function() {
            window.print();
            window.onafterprint = function() { window.close(); };
          };
        </script>
      </body>
    </html>
  `);
  printWindow.document.close();
}
